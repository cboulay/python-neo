    @staticmethod
    def _written_ahead(order, at, by):
        """`order` with the packet `by` places after `at` written at `at`, the ones between one place later."""
        order = np.array(order)
        order[at : at + by + 1] = np.r_[order[at + by], order[at : at + by]]
        return order

