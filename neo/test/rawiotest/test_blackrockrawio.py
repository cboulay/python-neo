    def test_get_blackrock_timestamps_ptp_with_gaps(self):
        """Test _get_blackrock_timestamps for PTP format with gaps and multiple segments."""
        dirname = self.get_local_path("blackrock/blackrock_ptp_with_missing_samples/Hub1-NWBtestfile_neural_wspikes")
        gap_tolerance_ms = 0.5
        reader = BlackrockRawIO(filename=dirname, nsx_to_load=6, gap_tolerance_ms=gap_tolerance_ms)
        reader.parse_header()

        n_segments = reader.segment_count(0)
        self.assertEqual(n_segments, 3)

        nanoseconds_per_second = 1_000_000_000.0

        # This file has a single stream: ns6 (30 kHz, 1 channel)
        stream_index = 0
        expected_sizes = [632, 58, 310]

        # First 5 PTP clock values (nanoseconds since Unix epoch) per segment, read directly from file and hardcoded here for testing
        first_5_ptp_clock_ns_per_segment = [
            np.array(
                [
                    1752531864717743037,
                    1752531864717776237,
                    1752531864717809677,
                    1752531864717843077,
                    1752531864717876277,
                ],
                dtype="uint64",
            ),
            np.array(
                [
                    1752531864739742985,
                    1752531864739776305,
                    1752531864739809665,
                    1752531864739842945,
                    1752531864739876385,
                ],
                dtype="uint64",
            ),
            np.array(
                [
                    1752531864740742986,
                    1752531864740776306,
                    1752531864740809626,
                    1752531864740842946,
                    1752531864740876346,
                ],
                dtype="uint64",
            ),
        ]
        # Last PTP clock value (nanoseconds since Unix epoch) of each segment, hardcoded here for testing
        last_ptp_clock_ns_per_segment = np.array(
            [1752531864738776304, 1752531864739709625, 1752531864751042999],
            dtype="uint64",
        )

        for seg_index in range(n_segments):
            timestamps = reader._get_blackrock_timestamps(0, seg_index, None, None, stream_index)
            self.assertEqual(timestamps.shape[0], expected_sizes[seg_index])

            # Verify first 5 timestamps match the clock values from the file
            expected_first_5 = first_5_ptp_clock_ns_per_segment[seg_index].astype("float64") / nanoseconds_per_second
            np.testing.assert_array_equal(timestamps[:5], expected_first_5)

            # Verify last timestamp
            expected_last = last_ptp_clock_ns_per_segment[seg_index].astype("float64") / nanoseconds_per_second
            np.testing.assert_array_equal(timestamps[-1], expected_last)

        # Verify the gaps between segments exceed the tolerance
        for seg_index in range(n_segments - 1):
            last_ts = last_ptp_clock_ns_per_segment[seg_index].astype("float64") / nanoseconds_per_second
            first_ts_next = (
                first_5_ptp_clock_ns_per_segment[seg_index + 1][0].astype("float64") / nanoseconds_per_second
            )
            gap_ms = (first_ts_next - last_ts) * 1000
            self.assertGreater(gap_ms, gap_tolerance_ms)

    def test_gap_tolerance_ms_parameter(self):
        """
        Test gap_tolerance_ms parameter for gap handling with files that have actual gaps.

        Tests the error-by-default behavior where files with timestamp gaps raise ValueError
        unless the user explicitly opts in with gap_tolerance_ms parameter.

        See PR #1769 for the gap details on the example file used here.
        """
        # Use stubbed files with missing samples (timestamp gaps) from SimulatedSpikes data
        dirname = self.get_local_path("blackrock/blackrock_ptp_with_missing_samples/Hub1-NWBtestfile_neural_wspikes")

        # Test 1: Default behavior (None) raises ValueError for files with gaps
        # This is the error-by-default behavior to ensure users are aware of data issues
        with self.assertRaises(ValueError) as context:
            reader = BlackrockRawIO(filename=dirname, nsx_to_load=6)
            reader.parse_header()

        # Test 2: Explicit tolerance allows loading files with gaps
        # User opts in by providing gap_tolerance_ms
        reader_with_tolerance = BlackrockRawIO(filename=dirname, nsx_to_load=6, gap_tolerance_ms=10.0)
        reader_with_tolerance.parse_header()
        segments_with_tolerance = reader_with_tolerance.segment_count(0)
        self.assertEqual(1, segments_with_tolerance)  # Gaps < 10ms are ignored

        # Test 3: Stricter tolerance creates 3 segments
        # With strict tolerance (0.5ms), gaps > 0.5ms will create new segments
        reader_strict = BlackrockRawIO(filename=dirname, nsx_to_load=6, gap_tolerance_ms=0.5)
        reader_strict.parse_header()
        segments_strict = reader_strict.segment_count(0)
        self.assertEqual(segments_strict, 3)  #

    def test_nev_segments_ignore_order_between_packet_types(self):
        """
        Comments are stamped when the user starts writing but written to the file when they finish, so they
        come after spikes with later timestamps. Only a packet earlier than the previous packet of its own
        type is a clock reset, and one reset is one segment boundary.
        """
        spike, comment = 1, 0xFFFF
        # The comments are 2 ticks ahead of the spike before them, later than the spike after them.
        no_reset = [(1000, spike), (1002, comment), (1001, spike), (1010, spike), (1012, comment), (1011, spike)]
        # A reset sends the clock of every packet type back.
        reset = [(5, spike), (7, comment), (6, spike)]
        reader = BlackrockRawIO(filename=self.get_local_path("blackrock/blackrock_3_0/file_spec_3_0"))  # not parsed
        for packets, expected in ((no_reset, [0] * 6), (no_reset + reset, [0] * 6 + [1] * 3)):
            raw = np.array(
                [(*p, b"") for p in packets], dtype=[("timestamp", "uint64"), ("packet_id", "uint16"), ("value", "S2")]
            )
            masks = {"Spikes": raw["packet_id"] == spike, "Comments": raw["packet_id"] == comment}
            with warnings.catch_warnings(record=True) as caught:
                warnings.simplefilter("always")
                segment_ids = reader._get_event_segment_ids(raw, masks, "3.0")
            assert_equal(segment_ids, expected)
            self.assertEqual(reader._nb_segment_nev, max(expected) + 1)
            self.assertEqual(len(caught), max(expected))  # one warning for the reset without a reset comment

    def test_nev_spikes_at_segment_edges_ptp(self):
        """
        With 1 ns timestamps (PTP files), converting the segment bounds to ticks or comparing uint64 with
        floats drops spikes at the edge of a segment. The NEV alone of this file has 4 segments.
        """
        reader = BlackrockRawIO(
            filename=self.get_local_path(
                "blackrock/blackrock_ptp_with_missing_samples/Hub1-NWBtestfile_neural_wspikes"
            ),
            nsx_to_load=[],
        )
        reader.parse_header()
        all_spikes, segment_ids = reader.nev_data["Spikes"]
        for seg_index in range(reader.segment_count(0)):
            t_start, t_stop = reader.segment_t_start(0, seg_index), reader.segment_t_stop(0, seg_index)
            for unit_index, (channel_id, unit_id) in enumerate(reader.internal_unit_ids):
                in_segment = all_spikes["timestamp"][
                    (all_spikes["packet_id"] == channel_id)
                    & (all_spikes["unit_class_nb"] == unit_id)
                    & (segment_ids == seg_index)
                ]
                for bounds in ((None, None), (t_start, t_stop + 1e-5)):
                    spikes = reader.get_spike_timestamps(0, seg_index, unit_index, *bounds)
                    assert_equal(spikes, in_segment)
                self.assertEqual(reader.spike_count(0, seg_index, unit_index), len(in_segment))
                # t_stop is exclusive
                exclusive = reader.get_spike_timestamps(0, seg_index, unit_index, t_start, t_stop)
                self.assertLessEqual(len(in_segment) - len(exclusive), 1)

    def test_nev_22_reads_spikes_on_electrodes_above_255(self):
        """
        A FileSpec 2.2 NEV with spikes on an electrode above 255 (Ripple Trellis numbers its front-end ports
        1-128, 129-256, 257-384...) keeps them, as 2.3 does (NeuralEnsemble/python-neo#1918). Built from neo's
        2.3 test NEV: marked 2.2, with electrode 1 renumbered 300 in its NEUEVWAV header and spike packets.
        """
        source_base = self.get_local_path("blackrock/FileSpec2.3001")
        original = BlackrockRawIO(filename=source_base, nsx_to_load=None)
        original.parse_header()
        units_on_1 = [i for i, (channel, _) in enumerate(original.internal_unit_ids) if channel == 1]
        self.assertTrue(units_on_1)  # electrode 1 has spikes to move
        expected = np.concatenate([original.get_spike_timestamps(0, 0, i, None, None) for i in units_on_1])

        data = bytearray(Path(source_base + ".nev").read_bytes())
        data[9] = 2  # FileSpec 2.3 -> 2.2
        header_size, packet_size = np.frombuffer(bytes(data[12:20]), dtype="<u4")
        for at in range(336, int(header_size), 32):  # extended headers follow the 336-byte basic header
            if data[at : at + 8] == b"NEUEVWAV" and int.from_bytes(data[at + 8 : at + 10], "little") == 1:
                data[at + 8 : at + 10] = (300).to_bytes(2, "little")
        # 2.x packets: a uint32 timestamp, then the uint16 packet id
        for at in range(int(header_size), len(data) - int(packet_size) + 1, int(packet_size)):
            if int.from_bytes(data[at + 4 : at + 6], "little") == 1:
                data[at + 4 : at + 6] = (300).to_bytes(2, "little")

        with tempfile.TemporaryDirectory() as folder:
            base = str(Path(folder) / "trellis_like")
            Path(base + ".nev").write_bytes(bytes(data))
            reader = BlackrockRawIO(filename=base, nsx_to_load=None)
            reader.parse_header()
        self.assertEqual(reader._nev_spec, "2.2")
        units_on_300 = [i for i, (channel, _) in enumerate(reader.internal_unit_ids) if channel == 300]
        self.assertTrue(units_on_300, "no spike channel on electrode 300")
        got = np.concatenate([reader.get_spike_timestamps(0, 0, i, None, None) for i in units_on_300])
        assert_equal(np.sort(got), np.sort(expected))

    def _open_local_and_from_memory(self, entity, nev_packets_per_piece=None, **kwargs):
        """Open a recording locally and, after copying its files into fsspec's memory filesystem, by memory:// URL."""
        import fsspec

        fs = fsspec.filesystem("memory")
        local_base = self.get_local_path(entity)
        for ext in [".ns1", ".ns2", ".ns3", ".ns4", ".ns5", ".ns6", ".nev"]:
            local_file = Path(local_base + ext)
            if local_file.exists() and not fs.exists(f"/{entity}{ext}"):
                fs.pipe(f"/{entity}{ext}", local_file.read_bytes())
                self.addCleanup(fs.rm, f"/{entity}{ext}")
        local = BlackrockRawIO(filename=local_base, **kwargs)
        local.parse_header()
        remote = BlackrockRawIO(filename=f"memory:///{entity}", **kwargs)
        if nev_packets_per_piece:
            remote._nev_packets_per_piece = nev_packets_per_piece
        remote.parse_header()
        # Tiny pieces test the open-time scan across piece boundaries; the per-unit reads after
        # it use the same code, so larger pieces keep the tests fast.
        remote._nev_packets_per_piece = 4096
        return local, remote

    def _assert_same_spikes_and_events(self, local, remote):
        """Every unit and event channel gives the same counts, times, waveforms and labels in every segment."""
        for seg_index in range(local.segment_count(0)):
            for unit_index in range(local.spike_channels_count()):
                self.assertEqual(
                    remote.spike_count(0, seg_index, unit_index), local.spike_count(0, seg_index, unit_index)
                )
                assert_equal(
                    remote.get_spike_timestamps(0, seg_index, unit_index, None, None),
                    local.get_spike_timestamps(0, seg_index, unit_index, None, None),
                )
                assert_equal(
                    remote.get_spike_raw_waveforms(0, seg_index, unit_index, None, None),
                    local.get_spike_raw_waveforms(0, seg_index, unit_index, None, None),
                )
            for event_index in range(local.event_channels_count()):
                self.assertEqual(
                    remote.event_count(0, seg_index, event_index), local.event_count(0, seg_index, event_index)
                )
                remote_times, _, remote_labels = remote.get_event_timestamps(0, seg_index, event_index, None, None)
                local_times, _, local_labels = local.get_event_timestamps(0, seg_index, event_index, None, None)
                assert_equal(remote_times, local_times)
