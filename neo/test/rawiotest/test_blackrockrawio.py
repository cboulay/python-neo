    def test_nev_segments_ignore_order_between_packet_types(self):
        """
        Only a packet earlier than the previous packet of its own type is a clock reset.

        Central writes a comment a few ms after stamping it, so in this file two comments are
        written before 96 spikes stamped 2.1 ms earlier. Comparing packets of different types
        split the nev into two segments, and with the ns5 only the 384 spikes of the first one
        were returned. Comments are not in time order among themselves either, so they are not
        compared at all; a reset still splits.
        """
        filename = self.get_local_path(
            "blackrock/version_3_0/time_structure/comment_written_before_earlier_spikes/"
            "comment_written_before_earlier_spikes"
        )
        for nsx_to_load in ([], [5]):
            reader = BlackrockRawIO(filename=filename, nsx_to_load=nsx_to_load)
            reader.parse_header()
            self.assertEqual(reader.segment_count(0), 1)
            returned = sum(
                reader.get_spike_timestamps(0, 0, unit_index, None, None).size
                for unit_index in range(reader.spike_channels_count())
            )
            self.assertEqual(returned, 960)

        # The second comment is earlier than the first: no split. Then a reset sends the spikes' clock back.
        spike, comment, t = 1, 0xFFFF, 10**12  # t: 1000 s at 1 ns per tick
        packets = [(t, spike), (t + 4, comment), (t + 1, spike), (t + 2, comment), (t + 3, spike)]
        packets += [(5, spike), (3, comment), (6, spike)]
        raw = np.array([(*p, b"") for p in packets], dtype=[("timestamp", "u8"), ("packet_id", "u2"), ("value", "S2")])
        masks = {"Spikes": raw["packet_id"] == spike, "Comments": raw["packet_id"] == comment}
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            assert_equal(reader._get_event_segment_ids(raw, masks, "3.0"), [0] * 5 + [1] * 3)

        # A spike stamped up to 10 ms before the previous spike on its electrode was written late: no reset.
        # Spikes on other electrodes are not compared (#1755: up to 15 ms out of order between electrodes).
        window = round(0.010 * float(reader._nev_basic_header["timestamp_resolution"]))
        # electrode 1 back 10 ms; electrode 2 15 ms behind electrode 1; electrode 1 back 10 ms and one tick
        spikes = [(10 * window, 1), (9 * window, 1), (20 * window, 1), (37 * window // 2, 2), (21 * window, 1)]
        spikes += [(20 * window - 1, 1)]
        raw = np.array([(*p, b"") for p in spikes], dtype=[("timestamp", "u8"), ("packet_id", "u2"), ("value", "S2")])
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            segment_ids = reader._get_event_segment_ids(raw, {"Spikes": raw["packet_id"] > 0}, "3.0")
        assert_equal(segment_ids, [0, 0, 0, 0, 0, 1])
        self.assertEqual(reader.nev_reordered_packets, 1)

